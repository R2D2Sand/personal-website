import assert from 'node:assert/strict'
const response = await fetch('http://127.0.0.1:3100/api/veyra')
assert.equal(response.status, 200)
assert.ok(response.headers.get('cache-control').includes('no-store'))
const data = await response.json()
assert.ok(['snapshot', 'remote', 'unavailable'].includes(data.connection))
const body = JSON.stringify(data)
assert.ok(!body.includes('private_key_path'))
assert.ok(!body.includes('C:\\Users'))
assert.ok(!body.includes('VEYRA_DASHBOARD_PASSWORD'))
const page = await fetch('http://127.0.0.1:3100/veyra')
assert.equal(page.status, 200)
const html = await page.text()
assert.ok(!html.includes('type="password"'))
assert.ok(html.includes('A clearer view'))
console.log('Public page and API checks passed without cookies or login; no private paths or credentials exposed.')
